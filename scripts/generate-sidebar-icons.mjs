// Copies the dashboard sidebar's Fluent Color icons out of Iconify's
// @iconify-json/fluent-color set (a dev dependency) into a small local
// module, so the app neither bundles the whole set nor fetches icons from
// the Iconify API at runtime. Re-run after changing ICONS:
//   pnpm icons:sidebar
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const ICONS = {
  dashboard: "apps-20",
  consultations: "calendar-checkmark-20",
  leads: "person-add-20",
  clients: "people-20",
  offers: "document-text-20",
  pricelist: "receipt-20",
  media: "image-20",
  team: "people-team-20",
  seo: "search-sparkle-20",
  admin: "shield-checkmark-20",
  settings: "settings-20",
};

const require = createRequire(import.meta.url);
const set = JSON.parse(
  readFileSync(require.resolve("@iconify-json/fluent-color/icons.json"), "utf8"),
);

const entries = Object.entries(ICONS).map(([key, name]) => {
  const icon = set.icons[name];
  if (!icon) throw new Error(`fluent-color:${name} not found`);
  const data = {
    body: icon.body,
    width: icon.width ?? set.width ?? 16,
    height: icon.height ?? set.height ?? 16,
  };
  return `  // fluent-color:${name}\n  ${key}: ${JSON.stringify(data)},`;
});

const out = `// Generated by scripts/generate-sidebar-icons.mjs — do not edit by hand.
// Fluent Color icons by Microsoft (MIT), via Iconify.
import type { SidebarIconData } from "@/components/dashboard/sidebar-icon";

const sidebarIcons = {
${entries.join("\n")}
} satisfies Record<string, SidebarIconData>;

export { sidebarIcons };
`;

writeFileSync("src/components/dashboard/sidebar-icons.ts", out);
console.log(`Wrote ${entries.length} icons to src/components/dashboard/sidebar-icons.ts`);
